#!/usr/bin/env python3
"""Packs web/device.html into firmware/src/web_page.h (gzipped) so the board can serve it."""
import gzip, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
raw = (root / "web" / "device.html").read_bytes()
gz = gzip.compress(raw, 9, mtime=0)
lines = [", ".join(f"0x{b:02x}" for b in gz[i:i + 20]) for i in range(0, len(gz), 20)]
out = ("// Generated by tools/build_web.py from web/device.html - don't edit by hand\n#pragma once\n#include <Arduino.h>\n"
       f"const size_t WEB_PAGE_GZ_LEN = {len(gz)};\nconst uint8_t WEB_PAGE_GZ[] PROGMEM = {{\n" + ",\n".join(lines) + "\n};\n")
(root / "firmware" / "HeltecScout" / "web_page.h").write_text(out)
print(f"web_page.h: {len(raw)} bytes -> {len(gz)} gzipped")
